// The journal envelope: the shape of one entry in one stream's log. The rule:
// a log holds facts someone or something stated, never the work state derived
// from them. The journal knows no stream, no event type and no origin of its
// own; modules name all three. Pure tier, so every timestamp and id arrives as
// an argument.

/**
 * Envelope shape version; bumped only when `JournalRow`'s own fields change, never
 * for a payload change, which bumps that type's `v` in `catalogue.ts`.
 */
export const ENVELOPE_VERSION = 1;

/**
 * Hard ceiling on one row's serialized payload, so a blob in an event is found at
 * the append site rather than in production. A log stores facts, not bytes.
 */
export const PAYLOAD_MAX_BYTES = 64 * 1024;

/**
 * Which log an event belongs to: everything with the same pair folds together.
 * The type names a kind of log (a module declares it with `defineStream`); the
 * id names one log of that kind.
 */
export interface StreamRef {
  streamType: string;
  streamId: string;
}

/**
 * Declare a kind of stream. The owning module states it once,
 * `export const { type, of } = defineStream("order")`, and writers address one
 * log with `of(id)`; `type` keeps its literal, so an event pinned to the stream
 * is pinned at compile time.
 */
export function defineStream<const T extends string>(type: T) {
  return {
    type,
    of: (streamId: string): { streamType: T; streamId: string } => ({ streamType: type, streamId }),
  };
}

/**
 * One stored entry; append-only, partitioned by stream. A stream's id should be
 * an id the writer controls, not one borrowed from outside, so correcting an
 * outside pairing never rewrites the log.
 */
export interface JournalRow extends StreamRef {
  /**
   * Global autoincrement: **arrival order, not occurrence order**. A total order
   * with no read-before-write; per-stream expected-version checks are only worth
   * having with multiple independent writers.
   */
  seq?: number;
  /**
   * Identifies this one event, unique across the journal. Its job is
   * de-duplication: a second append with the same id stores nothing. It says
   * nothing about which log the event is in; that is the stream's job.
   */
  eventId: string;
  /**
   * Stable domain name, e.g. `"order.placed"`; not a transport's message name, so
   * renaming an endpoint does not need an upcaster. `via` keeps the link back.
   */
  type: string;
  /** Payload version, **per `type`**. See `catalogue.ts`. */
  v: number;
  /** Envelope version. `ENVELOPE_VERSION` at write time. */
  ev: number;
  /** ISO-8601: when the thing happened. The reducer's only clock. */
  at: string;
  /**
   * ISO-8601: when this row was appended. Differs from `at` for relayed facts, e.g.
   * a fact relayed from a device and appended later.
   */
  recordedAt: string;
  /** Who stated it; the vocabulary is the application's, so the journal stores any string. */
  origin: string;
  /** Validated against the schema for `(type, v)` at append **and** at read. */
  payload: Record<string, unknown>;
  /**
   * The transport this arrived on; **diagnostics only**. No reducer may read it,
   * or the projection depends on which runtime served a call.
   */
  via?: string;
  /** The `seq` of the command that caused this observation, when known. */
  causedBy?: number;
}

/**
 * An entry about to be appended; `seq`, `ev` and `recordedAt` are the writer's.
 * Writers build it through a definition's `EventOf` type (`events.ts`), not by hand.
 */
export interface NewEvent<T = Record<string, unknown>> extends StreamRef {
  /**
   * Generated by the append path when absent. Pass one to make a retry
   * idempotent: the second append returns the stored row instead of a copy.
   */
  eventId?: string;
  type: string;
  /**
   * The payload version the writer built. Must equal the version the catalogue
   * writes for `type`, or the append is refused: a writer still building an old
   * shape is caught at the append, not when a fold misreads it.
   */
  v: number;
  payload: T;
  origin: string;
  /**
   * When it happened; defaults to the append clock. **Pass it explicitly for any
   * observation of a past moment**, or relay delay shifts it silently.
   */
  at?: string;
  via?: string;
  causedBy?: number;
}
